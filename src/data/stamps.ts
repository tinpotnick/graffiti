// Parses 16×16 ASCII art into Uint8Array.
// . = transparent (0), # = primary colour (1), o = secondary/highlight (2)
function s(art: string): Uint8Array {
  const data = new Uint8Array(256);
  let i = 0;
  for (const ch of art) {
    if (ch === "\n" || ch === " ") continue;
    if (i >= 256) break;
    data[i++] = ch === "#" ? 1 : ch === "o" ? 2 : 0;
  }
  return data;
}

